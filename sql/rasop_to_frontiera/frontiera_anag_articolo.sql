INSERT INTO hcbi_ras.frontiera_anag_articolo (
    id, anno, codice, livello, nome, descrizione, eliminato,
    prezzo_regionale, unita_misura, macro_gruppo, spese_generali,
    di_cui_analisi, utile_impresa, last_update, analisi_approvata,
    has_utile_impresa, analisi_pubblicata, addendum, is_analisi,
    is_cam, is_ufficiale, id_categoria, is_manodopera, codice_lev1,
    codice_lev2, codice_lev3, codice_lev4, codice_lev5, is_minuteria,
    percentuale_aumento, annotazione, esporta_come_articolo,
    escludi_manodopera
)
SELECT
    a.id::character varying(100) AS id,
    a.anno::character varying(100) AS anno,
    a.codice::character varying(60) AS codice,
    a.livello::character varying(20) AS livello,
    a.nome,
    a.descrizione,
    a.eliminato::character varying(20) AS eliminato,
    a.prezzo_regionale::character varying(20) AS prezzo_regionale,
    a.unita_misura::character varying(100) AS unita_misura,
    a.macro_gruppo::character varying(20) AS macro_gruppo,
    a.spese_generali::character varying(100) AS spese_generali,
    a.di_cui_analisi::character varying(100) AS di_cui_analisi,
    a.utile_impresa::character varying(100) AS utile_impresa,
    a.last_update,
    a.analisi_approvata::character varying(20) AS analisi_approvata,
    a.has_utile_impresa::character varying(20) AS has_utile_impresa,
    a.analisi_pubblicata::character varying(20) AS analisi_pubblicata,
    a.addendum::character varying(20) AS addendum,
    a.is_analisi::character varying(20) AS is_analisi,
    a.is_cam::character varying(20) AS is_cam,
    a.is_ufficiale::character varying(20) AS is_ufficiale,
    a.id_categoria::character varying(100) AS id_categoria,
    a.is_manodopera::character varying(20) AS is_manodopera,
    a.codice_lev1,
    a.codice_lev2,
    a.codice_lev3,
    a.codice_lev4,
    a.codice_lev5,
    a.is_minuteria::character varying(20) AS is_minuteria,
    a.percentuale_aumento::character varying(100) AS percentuale_aumento,
    a.annotazione,
    CASE WHEN a.esporta_come_articolo IS TRUE THEN '1' WHEN a.esporta_come_articolo IS FALSE THEN '0' END::character varying(20) AS esporta_come_articolo,
    CASE WHEN a.escludi_manodopera IS TRUE THEN '1' WHEN a.escludi_manodopera IS FALSE THEN '0' END::character varying(20) AS escludi_manodopera
FROM public.articoli AS a
ORDER BY a.id;
