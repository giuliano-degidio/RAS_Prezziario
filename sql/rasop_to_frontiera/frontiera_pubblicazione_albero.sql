INSERT INTO hcbi_ras.frontiera_pubblicazione_albero (
    anno, provincia, codice, descrizione, prezzo, idum, isanalisi,
    isincidenza, addendum, scostamento, scostamento_con_spese,
    is_nuovo_codice, is_prezzo_modificato, is_prezzo_con_spese_modificato,
    is_analisi_modificata, is_descrizione_modificata,
    is_uinta_misura_modificata, is_spese_generali_modificate,
    is_utili_impresa_modificati, is_oneri_sicurezza_modificati,
    descrizione_de, is_ufficiale, id_categoria, nome, nome_de,
    is_nome_modificato, link_cam, annotazione, annotazione_de, id,
    esporta_come_articolo, escludi_manodopera, mostra_struttura_analisi,
    macro_gruppo, is_cam
)
SELECT
    pa.anno::character varying(100) AS anno,
    pa.provincia::character varying(100) AS provincia,
    pa.codice,
    pa.descrizione,
    pa.prezzo::character varying(100) AS prezzo,
    pa.idum::character varying(100) AS idum,
    pa.isanalisi::character varying(20) AS isanalisi,
    pa.isincidenza::character varying(20) AS isincidenza,
    pa.addendum::character varying(20) AS addendum,
    pa.scostamento::character varying(100) AS scostamento,
    pa.scostamento_con_spese::character varying(100) AS scostamento_con_spese,
    pa.is_nuovo_codice::character varying(20) AS is_nuovo_codice,
    pa.is_prezzo_modificato::character varying(20) AS is_prezzo_modificato,
    pa.is_prezzo_con_spese_modificato::character varying(20) AS is_prezzo_con_spese_modificato,
    pa.is_analisi_modificata::character varying(20) AS is_analisi_modificata,
    pa.is_descrizione_modificata::character varying(20) AS is_descrizione_modificata,
    pa.is_uinta_misura_modificata::character varying(20) AS is_uinta_misura_modificata,
    pa.is_spese_generali_modificate::character varying(20) AS is_spese_generali_modificate,
    pa.is_utili_impresa_modificati::character varying(20) AS is_utili_impresa_modificati,
    pa.is_oneri_sicurezza_modificati::character varying(20) AS is_oneri_sicurezza_modificati,
    pa.descrizione_de,
    pa.is_ufficiale::character varying(20) AS is_ufficiale,
    pa.id_categoria::character varying(20) AS id_categoria,
    pa.nome,
    pa.nome_de,
    pa.is_nome_modificato::character varying(20) AS is_nome_modificato,
    pa.link_cam,
    pa.annotazione,
    pa.annotazione_de,
    pa.id::character varying(100) AS id,
    CASE WHEN pa.esporta_come_articolo IS TRUE THEN '1' WHEN pa.esporta_come_articolo IS FALSE THEN '0' END::character varying(20) AS esporta_come_articolo,
    CASE WHEN pa.escludi_manodopera IS TRUE THEN '1' WHEN pa.escludi_manodopera IS FALSE THEN '0' END::character varying(20) AS escludi_manodopera,
    CASE WHEN pa.mostra_struttura_analisi IS TRUE THEN '1' WHEN pa.mostra_struttura_analisi IS FALSE THEN '0' END::character varying(20) AS mostra_struttura_analisi,
    pa.macro_gruppo::character varying(20) AS macro_gruppo,
    pa.is_cam::character varying(20) AS is_cam
FROM public.pubblicazione_albero AS pa
ORDER BY pa.anno, pa.provincia, pa.codice;
