CREATE OR REPLACE VIEW "hcbi_ras"."v_src_tmp_pubblicazione_albero" AS
 SELECT TRIM(BOTH FROM anno::text) AS ds_anno_pubblicazione,
    TRIM(BOTH FROM provincia::text) AS id_sorgente_provincia,
    TRIM(BOTH FROM codice::text) AS cd_articolo,
    TRIM(BOTH FROM descrizione) AS ds_articolo,
    TRIM(BOTH FROM prezzo::text) AS nr_prezzo,
    TRIM(BOTH FROM idum::text) AS id_sorgente_um,
    TRIM(BOTH FROM isanalisi::text) AS fl_isanalisi,
    TRIM(BOTH FROM isincidenza::text) AS fl_isincidenza,
    TRIM(BOTH FROM addendum::text) AS cd_versione,
    TRIM(BOTH FROM scostamento::text) AS nr_scostamento,
    TRIM(BOTH FROM scostamento_con_spese::text) AS nr_scostamento_con_spese,
    TRIM(BOTH FROM is_nuovo_codice::text) AS fl_is_nuovo_codice,
    TRIM(BOTH FROM is_prezzo_modificato::text) AS fl_is_prezzo_modificato,
    TRIM(BOTH FROM is_prezzo_con_spese_modificato::text) AS fl_is_prezzo_con_spese_modificato,
    TRIM(BOTH FROM is_analisi_modificata::text) AS fl_is_analisi_modificata,
    TRIM(BOTH FROM is_descrizione_modificata::text) AS fl_is_descrizione_modificata,
    TRIM(BOTH FROM is_uinta_misura_modificata::text) AS fl_is_uinta_misura_modificata,
    TRIM(BOTH FROM is_spese_generali_modificate::text) AS fl_is_spese_generali_modificate,
    TRIM(BOTH FROM is_utili_impresa_modificati::text) AS fl_is_utili_impresa_modificati,
    TRIM(BOTH FROM is_oneri_sicurezza_modificati::text) AS fl_is_oneri_sicurezza_modificati,
    TRIM(BOTH FROM descrizione_de) AS ds_descrizione_de,
    TRIM(BOTH FROM is_ufficiale::text) AS fl_is_ufficiale,
    TRIM(BOTH FROM id_categoria::text) AS id_sorgente_categoria,
    TRIM(BOTH FROM nome) AS ds_nome,
    TRIM(BOTH FROM nome_de) AS ds_nome_de,
    TRIM(BOTH FROM is_nome_modificato::text) AS fl_is_nome_modificato,
    TRIM(BOTH FROM link_cam::text) AS ds_link_cam,
    TRIM(BOTH FROM annotazione) AS ds_annotazione,
    TRIM(BOTH FROM annotazione_de) AS ds_annotazione_de,
    TRIM(BOTH FROM id::text) AS id_sorgente_pubblicazione_albero,
    TRIM(BOTH FROM esporta_come_articolo::text) AS fl_esporta_come_articolo,
    TRIM(BOTH FROM escludi_manodopera::text) AS fl_escludi_manodopera,
    TRIM(BOTH FROM mostra_struttura_analisi::text) AS fl_mostra_struttura_analisi,
    TRIM(BOTH FROM macro_gruppo::text) AS nr_macro_gruppo,
    TRIM(BOTH FROM is_cam::text) AS fl_is_cam
   FROM hcbi_ras.src_tmp_pubblicazione_albero srctpa;;
