CREATE OR REPLACE VIEW "hcbi_ras"."v_src_tmp_anag_articolo" AS
 SELECT TRIM(BOTH FROM id::text) AS id_sorgente_articolo,
    TRIM(BOTH FROM anno::text) AS ds_anno,
    TRIM(BOTH FROM codice::text) AS cd_articolo,
    TRIM(BOTH FROM livello::text) AS nr_livello,
    TRIM(BOTH FROM nome) AS ds_nome,
    TRIM(BOTH FROM descrizione) AS ds_descrizione,
    TRIM(BOTH FROM eliminato::text) AS fl_eliminato,
    TRIM(BOTH FROM prezzo_regionale::text) AS fl_prezzo_regionale,
    TRIM(BOTH FROM unita_misura::text) AS ds_unita_misura,
    TRIM(BOTH FROM macro_gruppo::text) AS nr_macro_gruppo,
    TRIM(BOTH FROM spese_generali::text) AS nr_spese_generali,
    TRIM(BOTH FROM di_cui_analisi::text) AS nr_di_cui_analisi,
    TRIM(BOTH FROM utile_impresa::text) AS nr_utile_impresa,
    last_update AS dt_last_update,
    TRIM(BOTH FROM analisi_approvata::text) AS fl_analisi_approvata,
    TRIM(BOTH FROM has_utile_impresa::text) AS fl_has_utile_impresa,
    TRIM(BOTH FROM analisi_pubblicata::text) AS fl_analisi_pubblicata,
    TRIM(BOTH FROM addendum::text) AS cd_versione,
    TRIM(BOTH FROM is_analisi::text) AS fl_is_analisi,
    TRIM(BOTH FROM is_cam::text) AS fl_is_cam,
    TRIM(BOTH FROM is_ufficiale::text) AS fl_is_ufficiale,
    TRIM(BOTH FROM id_categoria::text) AS id_sorgente_categoria,
    TRIM(BOTH FROM is_manodopera::text) AS fl_is_manodopera,
    TRIM(BOTH FROM codice_lev1::text) AS cd_codice_lev1,
    TRIM(BOTH FROM codice_lev2::text) AS cd_codice_lev2,
    TRIM(BOTH FROM codice_lev3::text) AS cd_codice_lev3,
    TRIM(BOTH FROM codice_lev4::text) AS cd_codice_lev4,
    TRIM(BOTH FROM codice_lev5::text) AS cd_codice_lev5,
    TRIM(BOTH FROM is_minuteria::text) AS fl_is_minuteria,
    TRIM(BOTH FROM percentuale_aumento::text) AS nr_percentuale_aumento,
    TRIM(BOTH FROM annotazione) AS ds_annotazione,
    TRIM(BOTH FROM esporta_come_articolo::text) AS fl_esporta_come_articolo,
    TRIM(BOTH FROM escludi_manodopera::text) AS fl_escludi_manodopera,
    TRIM(BOTH FROM provincia::text) AS id_sorgente_provincia
   FROM hcbi_ras.src_tmp_anag_articolo s;;
