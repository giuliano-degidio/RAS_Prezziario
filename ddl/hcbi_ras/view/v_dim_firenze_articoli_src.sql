CREATE OR REPLACE VIEW "hcbi_ras"."v_dim_firenze_articoli_src" AS
 SELECT id_firenze_articolo,
    nr_anno,
    ds_regione,
    ds_provincia,
    nr_riga_file,
    cd_codice_completo,
    SUBSTRING(cd_codice_completo FROM 7)::character varying(100) AS cd_articolo,
    fl_cam,
    ds_tipologia_famiglia,
    ds_capitolo,
    ds_voce,
    ds_articolo,
    cd_unita_misura,
    nr_prezzo_senza_sg_ui,
    nr_prezzo,
    nr_perc_spese_generali,
    nr_spese_generali,
    nr_perc_utili_impresa,
    nr_utili_impresa,
    nr_perc_oneri_sicurezza_impresa,
    nr_oneri_sicurezza_impresa,
    nr_incidenza_manodopera_indiretta,
    nr_manodopera_indiretta,
    nr_incidenza_manodopera_diretta,
    nr_manodopera_diretta,
    nr_incidenza_oneri_sicurezza_prezzo
   FROM hcbi_ras.dwh_firenze_articoli src
  WHERE id_firenze_articolo <> ALL (ARRAY[0::bigint, '-1'::integer::bigint]);;
