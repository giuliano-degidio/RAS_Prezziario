CREATE OR REPLACE VIEW "hcbi_ras"."v_src_tmp_pubblicazione_articoli" AS
 SELECT TRIM(BOTH FROM provincia::text) AS id_sorgente_provincia,
    TRIM(BOTH FROM anno::text) AS ds_anno_pubblicazione,
    TRIM(BOTH FROM codice_completo::text) AS cd_codice_completo,
    TRIM(BOTH FROM um::text) AS cd_unita_misura,
    TRIM(BOTH FROM prezzo::text) AS nr_prezzo,
    TRIM(BOTH FROM prezan::text) AS nr_prezzo_annuo,
    TRIM(BOTH FROM percsp::text) AS nr_perc_spese,
    TRIM(BOTH FROM percutil::text) AS nr_perc_utile,
    TRIM(BOTH FROM sicur::text) AS nr_sicur,
    TRIM(BOTH FROM percman::text) AS nr_perc_manodopera,
    TRIM(BOTH FROM perconeri::text) AS nr_perc_oneri,
    TRIM(BOTH FROM isanalisi::text) AS fl_isanalisi,
    TRIM(BOTH FROM prezman::text) AS nr_prezzo_manodopera,
    TRIM(BOTH FROM addendum::text) AS cd_versione,
    TRIM(BOTH FROM codice::text) AS cd_articolo,
    TRIM(BOTH FROM codice_1::text) AS cd_titolo,
    TRIM(BOTH FROM codice_2::text) AS cd_capitolo,
    TRIM(BOTH FROM codice_3::text) AS cd_sottocapitolo,
    TRIM(BOTH FROM codice_4::text) AS cd_categoria_articolo,
    TRIM(BOTH FROM codice_5::text) AS cd_subarticolo,
    TRIM(BOTH FROM um_de::text) AS ds_unita_misura_de,
    TRIM(BOTH FROM id_categoria::text) AS id_sorgente_categoria,
    TRIM(BOTH FROM is_minuteria::text) AS fl_is_minuteria,
    TRIM(BOTH FROM id::text) AS id_sorgente_pubblicazione_articoli,
    TRIM(BOTH FROM percman_diretta::text) AS nr_perc_manodopera_dir,
    TRIM(BOTH FROM prezman_diretta::text) AS nr_prezzo_manodopera_dir,
    TRIM(BOTH FROM ifc_scaricabile::text) AS fl_ifc_scaricabile,
    TRIM(BOTH FROM macro_gruppo::text) AS nr_macro_gruppo,
    TRIM(BOTH FROM spese::text) AS nr_spese,
    TRIM(BOTH FROM utili::text) AS nr_utili
   FROM hcbi_ras.src_tmp_pubblicazione_articoli s;;
