CREATE OR REPLACE VIEW "hcbi_ras"."v_src_tmp_anag_informatori" AS
 SELECT TRIM(BOTH FROM id::text) AS id_sorgente_informatore,
    TRIM(BOTH FROM ragione_sociale::text) AS ds_ragione_sociale,
    TRIM(BOTH FROM p_iva::text) AS cd_p_iva,
    TRIM(BOTH FROM codice_ateco_2002::text) AS cd_codice_ateco_2002,
    TRIM(BOTH FROM indirizzo_sede_legale::text) AS ds_indirizzo_sede_legale,
    TRIM(BOTH FROM cap_sede_legale::text) AS cd_cap_sede_legale,
    TRIM(BOTH FROM citta_sede_legale::text) AS ds_citta_sede_legale,
    TRIM(BOTH FROM provincia_sede_legale::text) AS cd_provincia_sede_legale,
    TRIM(BOTH FROM indirizzo_sede_operativa::text) AS ds_indirizzo_sede_operativa,
    TRIM(BOTH FROM cap_sede_operativa::text) AS cd_cap_sede_operativa,
    TRIM(BOTH FROM citta_sede_operativa::text) AS ds_citta_sede_operativa,
    TRIM(BOTH FROM provincia_sede_operativa::text) AS cd_provincia_sede_operativa,
    TRIM(BOTH FROM contatti) AS ds_contatti,
    TRIM(BOTH FROM stato::text) AS cd_stato,
    TRIM(BOTH FROM note) AS ds_note,
    TRIM(BOTH FROM stato_attivita::text) AS ds_stato_attivita,
    TRIM(BOTH FROM codice_fiscale::text) AS cd_codice_fiscale,
    TRIM(BOTH FROM anno::text) AS ds_anno_pubblicazione,
    TRIM(BOTH FROM last_update::text) AS dt_last_update,
    TRIM(BOTH FROM nazione::text) AS ds_nazione,
    TRIM(BOTH FROM addendum::text) AS cd_versione,
    TRIM(BOTH FROM provincia::text) AS id_sorgente_provincia,
    TRIM(BOTH FROM escludi_invio_mail_assoc_listino_completa::text) AS fl_escludi_invio_mail_assoc_listino_completa
   FROM hcbi_ras.src_tmp_anag_informatori s;;
