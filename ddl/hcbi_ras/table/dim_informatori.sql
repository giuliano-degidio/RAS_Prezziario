
CREATE TABLE hcbi_ras.dim_informatori (
	id_anag_informatore BIGINT NOT NULL, 
	id_sorgente_informatore INTEGER, 
	ds_ragione_sociale VARCHAR(100) NOT NULL, 
	cd_p_iva VARCHAR(100), 
	id_anag_ateco_2002 BIGINT NOT NULL, 
	ds_indirizzo_sede_legale VARCHAR(100), 
	cd_cap_sede_legale VARCHAR(10), 
	ds_citta_sede_legale VARCHAR(100), 
	cd_provincia_sede_legale VARCHAR(100), 
	ds_indirizzo_sede_operativa VARCHAR(100), 
	cd_cap_sede_operativa VARCHAR(10), 
	ds_citta_sede_operativa VARCHAR(100), 
	cd_provincia_sede_operativa VARCHAR(100), 
	ds_contatti TEXT, 
	cd_stato INTEGER, 
	ds_note TEXT, 
	ds_stato_attivita VARCHAR(100), 
	cd_codice_fiscale VARCHAR(100), 
	id_periodo_pubblicazione INTEGER NOT NULL, 
	dt_last_update TIMESTAMP WITHOUT TIME ZONE, 
	ds_nazione VARCHAR(40), 
	id_anag_versione BIGINT NOT NULL, 
	id_anag_provincia BIGINT NOT NULL, 
	fl_escludi_invio_mail_assoc_listino_completa INTEGER, 
	dt_creation TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_creation_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	dt_update TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_update_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	CONSTRAINT pk_dim_informatori PRIMARY KEY (id_anag_informatore), 
	CONSTRAINT fk_dim_informatori_ateco_2002 FOREIGN KEY(id_anag_ateco_2002) REFERENCES hcbi_ras.dim_ateco_2002 (id_anag_ateco_2002) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_informatori_periodo FOREIGN KEY(id_periodo_pubblicazione) REFERENCES hcbi_ras.dim_periodo (id_periodo) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_informatori_provincia FOREIGN KEY(id_anag_provincia) REFERENCES hcbi_ras.dim_provincia (id_anag_provincia) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_informatori_versione FOREIGN KEY(id_anag_versione) REFERENCES hcbi_ras.dim_versione (id_anag_versione) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT uq_dim_informatori UNIQUE NULLS NOT DISTINCT (ds_ragione_sociale, id_periodo_pubblicazione, id_anag_versione, id_anag_provincia)
);
