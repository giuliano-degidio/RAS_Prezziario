
CREATE TABLE hcbi_ras.dwh_firenze_analisi (
	id_firenze_analisi BIGSERIAL NOT NULL, 
	nr_anno INTEGER NOT NULL, 
	ds_regione VARCHAR(50) NOT NULL, 
	ds_provincia VARCHAR(50) NOT NULL, 
	nr_riga_file BIGINT NOT NULL, 
	cd_analisi VARCHAR(100) NOT NULL, 
	ds_analisi TEXT, 
	fl_cam VARCHAR(20), 
	cd_dettaglio VARCHAR(200) NOT NULL, 
	cd_dettaglio_cam VARCHAR(200), 
	ds_voce_articolo TEXT, 
	cd_collegato VARCHAR(200), 
	cd_unita_misura VARCHAR(50) NOT NULL, 
	nr_quantita NUMERIC(24, 6) NOT NULL, 
	nr_prezzo_unitario NUMERIC(24, 6) NOT NULL, 
	nr_importo NUMERIC(24, 6) NOT NULL, 
	tx_nome_file VARCHAR(255) NOT NULL, 
	dt_caricamento TIMESTAMP WITHOUT TIME ZONE, 
	tx_caricamento_by VARCHAR(100), 
	dt_creation TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_creation_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	dt_update TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_update_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	dt_reciclo TIMESTAMP WITHOUT TIME ZONE, 
	CONSTRAINT pk_dwh_firenze_analisi PRIMARY KEY (id_firenze_analisi), 
	CONSTRAINT uq_dwh_firenze_analisi UNIQUE NULLS NOT DISTINCT (nr_anno, cd_analisi, cd_dettaglio, nr_riga_file)
);
