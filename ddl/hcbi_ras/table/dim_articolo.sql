
CREATE TABLE hcbi_ras.dim_articolo (
	id_anag_articolo BIGINT NOT NULL, 
	id_sorgente_articolo BIGINT NOT NULL, 
	id_periodo_pubblicazione INTEGER NOT NULL, 
	cd_articolo VARCHAR(60) NOT NULL, 
	nr_livello INTEGER NOT NULL, 
	ds_nome TEXT NOT NULL, 
	ds_descrizione TEXT NOT NULL, 
	fl_eliminato SMALLINT NOT NULL, 
	fl_prezzo_regionale SMALLINT NOT NULL, 
	id_anag_unita_misura BIGINT NOT NULL, 
	id_anag_macro_gruppo BIGINT NOT NULL, 
	nr_spese_generali NUMERIC(24, 5), 
	nr_di_cui_analisi NUMERIC(24, 5), 
	nr_utile_impresa NUMERIC(24, 5), 
	dt_last_update TIMESTAMP WITHOUT TIME ZONE NOT NULL, 
	fl_analisi_approvata SMALLINT NOT NULL, 
	fl_has_utile_impresa SMALLINT NOT NULL, 
	fl_analisi_pubblicata SMALLINT NOT NULL, 
	id_anag_versione BIGINT NOT NULL, 
	fl_is_analisi SMALLINT NOT NULL, 
	fl_is_cam SMALLINT NOT NULL, 
	fl_is_ufficiale SMALLINT NOT NULL, 
	id_sorgente_categoria BIGINT, 
	fl_is_manodopera SMALLINT NOT NULL, 
	cd_codice_lev1 VARCHAR(60), 
	cd_codice_lev2 VARCHAR(60), 
	cd_codice_lev3 VARCHAR(60), 
	cd_codice_lev4 VARCHAR(60), 
	cd_codice_lev5 VARCHAR(60), 
	fl_is_minuteria SMALLINT NOT NULL, 
	nr_percentuale_aumento NUMERIC(24, 5), 
	ds_annotazione TEXT, 
	fl_esporta_come_articolo SMALLINT NOT NULL, 
	fl_escludi_manodopera SMALLINT NOT NULL, 
	id_anag_provincia BIGINT NOT NULL, 
	dt_creation TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_creation_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	dt_update TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_update_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	CONSTRAINT pk_dim_articolo PRIMARY KEY (id_anag_articolo), 
	CONSTRAINT fk_dim_articolo_macro_gruppo FOREIGN KEY(id_anag_macro_gruppo) REFERENCES hcbi_ras.dim_macro_gruppo (id_anag_macro_gruppo) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_articolo_periodo FOREIGN KEY(id_periodo_pubblicazione) REFERENCES hcbi_ras.dim_periodo (id_periodo) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_articolo_provincia FOREIGN KEY(id_anag_provincia) REFERENCES hcbi_ras.dim_provincia (id_anag_provincia) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_articolo_unita_misura FOREIGN KEY(id_anag_unita_misura) REFERENCES hcbi_ras.dim_unita_misura (id_anag_unita_misura) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT fk_dim_articolo_versione FOREIGN KEY(id_anag_versione) REFERENCES hcbi_ras.dim_versione (id_anag_versione) ON DELETE RESTRICT ON UPDATE RESTRICT, 
	CONSTRAINT uq_dim_articolo UNIQUE NULLS NOT DISTINCT (id_periodo_pubblicazione, cd_articolo, id_anag_versione, id_anag_provincia)
);
