	fl_isincidenza SMALLINT, 
	nr_scostamento DOUBLE PRECISION, 
	nr_scostamento_con_spese DOUBLE PRECISION, 
	fl_is_nuovo_codice SMALLINT, 
	fl_is_prezzo_modificato SMALLINT, 
