
CREATE TABLE hcbi_ras.dwh_firenze_articoli_rej (
	id_dwh_firenze_articoli_rej BIGSERIAL NOT NULL, 
	nr_anno TEXT, 
	ds_regione TEXT, 
	ds_provincia TEXT, 
	nr_riga_file TEXT, 
	cd_codice_completo TEXT, 
	fl_cam TEXT, 
	ds_tipologia_famiglia TEXT, 
	ds_capitolo TEXT, 
	ds_voce TEXT, 
	ds_articolo TEXT, 
	cd_unita_misura TEXT, 
	nr_prezzo_senza_sg_ui TEXT, 
	nr_prezzo TEXT, 
	nr_perc_spese_generali TEXT, 
	nr_spese_generali TEXT, 
	nr_perc_utili_impresa TEXT, 
	nr_utili_impresa TEXT, 
