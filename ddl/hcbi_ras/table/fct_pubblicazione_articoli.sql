
CREATE TABLE hcbi_ras.fct_pubblicazione_articoli (
	id_pubblicazione_articoli BIGINT NOT NULL, 
	id_periodo_pubblicazione INTEGER NOT NULL, 
	id_anag_provincia BIGINT NOT NULL, 
	id_anag_versione BIGINT NOT NULL, 
	id_anag_articolo BIGINT NOT NULL, 
	id_anag_tipologia BIGINT NOT NULL, 
	id_anag_capitolo BIGINT NOT NULL, 
	id_anag_sottocapitolo BIGINT NOT NULL, 
	id_anag_unita_misura BIGINT NOT NULL, 
	id_anag_macro_gruppo BIGINT NOT NULL, 
	cd_codice_completo VARCHAR(70) NOT NULL, 
	cd_categoria_articolo VARCHAR(10), 
	cd_subarticolo VARCHAR(10), 
	ds_unita_misura_de VARCHAR(20), 
	id_sorgente_categoria BIGINT, 
	id_sorgente_pubblicazione_articoli BIGINT, 
	nr_prezzo NUMERIC(24, 5), 
	nr_prezzo_annuo NUMERIC(24, 5), 
	nr_perc_spese NUMERIC(24, 5), 
	nr_perc_utile NUMERIC(10, 5), 
	nr_sicur NUMERIC(24, 5), 
	nr_perc_manodopera NUMERIC(10, 5), 
	nr_perc_oneri NUMERIC(10, 5), 
	nr_prezzo_manodopera NUMERIC(24, 5), 
	nr_perc_manodopera_dir NUMERIC(10, 5), 
	nr_prezzo_manodopera_dir NUMERIC(24, 5), 
	nr_spese NUMERIC(24, 5), 
	nr_utili NUMERIC(24, 5), 
	fl_isanalisi SMALLINT, 
	fl_is_minuteria SMALLINT, 
	fl_ifc_scaricabile SMALLINT, 
	dt_creation TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_creation_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	dt_update TIMESTAMP WITHOUT TIME ZONE DEFAULT clock_timestamp() NOT NULL, 
	tx_update_by VARCHAR(4000) DEFAULT CURRENT_USER NOT NULL, 
	dt_reciclo TIMESTAMP WITHOUT TIME ZONE, 
	CONSTRAINT pk_fct_pubblicazione_articoli PRIMARY KEY (id_pubblicazione_articoli), 
	CONSTRAINT fk_fct_pub_art_articolo FOREIGN KEY(id_anag_articolo) REFERENCES hcbi_ras.dim_articolo (id_anag_articolo), 
	CONSTRAINT fk_fct_pub_art_capitolo FOREIGN KEY(id_anag_capitolo) REFERENCES hcbi_ras.dim_capitolo (id_anag_capitolo), 
	CONSTRAINT fk_fct_pub_art_macro_gruppo FOREIGN KEY(id_anag_macro_gruppo) REFERENCES hcbi_ras.dim_macro_gruppo (id_anag_macro_gruppo), 
	CONSTRAINT fk_fct_pub_art_periodo FOREIGN KEY(id_periodo_pubblicazione) REFERENCES hcbi_ras.dim_periodo (id_periodo), 
	CONSTRAINT fk_fct_pub_art_provincia FOREIGN KEY(id_anag_provincia) REFERENCES hcbi_ras.dim_provincia (id_anag_provincia), 
	CONSTRAINT fk_fct_pub_art_sottocapitolo FOREIGN KEY(id_anag_sottocapitolo) REFERENCES hcbi_ras.dim_sottocapitolo (id_anag_sottocapitolo), 
	CONSTRAINT fk_fct_pub_art_tipologia FOREIGN KEY(id_anag_tipologia) REFERENCES hcbi_ras.dim_tipologia (id_anag_tipologia), 
	CONSTRAINT fk_fct_pub_art_unita_misura FOREIGN KEY(id_anag_unita_misura) REFERENCES hcbi_ras.dim_unita_misura (id_anag_unita_misura), 
	CONSTRAINT fk_fct_pub_art_versione FOREIGN KEY(id_anag_versione) REFERENCES hcbi_ras.dim_versione (id_anag_versione)
);
